export function getTranslation(key: string, lang: Language = 'en'): string {
  const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return langDict[key] || TRANSLATIONS.en[key] || key;
}

const RTL_LANGUAGES: Language[] = ['ar'];

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  currentLanguageOption: LanguageOption;
  isRTL: boolean;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key: string) => key,
  currentLanguageOption: SUPPORTED_LANGUAGES[0],
  isRTL: false
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('visor_selected_language');
    if (saved && ['en', 'sw', 'lg', 'fr', 'pt', 'ar'].includes(saved)) {
      return saved as Language;
    }
    return 'en';
  });

  const setLanguage = (newLang: Language) => {
    setLanguageState(newLang);
    localStorage.setItem('visor_selected_language', newLang);
  };

  const t = (key: string) => getTranslation(key, language);

  const currentLanguageOption = SUPPORTED_LANGUAGES.find(l => l.code === language) || SUPPORTED_LANGUAGES[0];
  const isRTL = RTL_LANGUAGES.includes(language);

  // Mirrors the whole layout for RTL languages: setting dir on <html> makes
  // every flexbox row (the vast majority of this app's layout) reverse
  // direction automatically per CSS spec, with no per-component rtl: classes
  // needed. lang is also updated for screen readers / font selection.
  useEffect(() => {
    document.documentElement.dir = isRTL ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }, [language, isRTL]);

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, currentLanguageOption, isRTL }}>
      {children}
    </LanguageContext.Provider>
  );
};

export function useLanguage() {
  return useContext(LanguageContext);
}
